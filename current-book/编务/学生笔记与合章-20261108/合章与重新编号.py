def fix_span(m,s):
    pre=s[max(0,m.start()-3):m.start()]
    if pre.endswith('原') or pre.endswith('当时为'): return m.group(0)
    body=m.group(2); nums=re.findall(r'\d+',body)
    if not any(int(x) in MM for x in nums): return m.group(0)
    new=[]
    def num(t):
        n=int(t.group(0));k=MM.get(n,n);new.append(k)
        return f"{k:0{len(t.group(0))}d}" if t.group(0).startswith('0') else str(k)
    b2=re.sub(r'\d+',num,body)
    if len(nums)>1 and new!=sorted(new) and not body.startswith('0'):
        it=iter(sorted(new)); b2=re.sub(r'\d+',lambda t:str(next(it)),body)
    return '第'+m.group(1)+b2+m.group(3)+'章'
def fix(s):
    out=[];last=0
    for m in pat.finditer(s):
        out.append(s[last:m.start()]);out.append(fix_span(m,s));last=m.end()
    out.append(s[last:]);return ''.join(out)

