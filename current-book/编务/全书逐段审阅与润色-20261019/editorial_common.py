def protect_spans(text: str):
    """保护代码块、行内代码、图片链接、Markdown链接和数学公式不被文本替换破坏。"""
    protected = []

    def _save(m):
        idx = len(protected)
        protected.append(m.group(0))
        return f"@@PROT_{idx}@@"

    # 保护 fenced code blocks
    text = re.sub(r"```[\s\S]*?```", _save, text)
    # 保护图片 ![alt](url) 的 (url) 部分，允许图注润色
    text = re.sub(
        r"(\!\[[^\]]*\])(\([^)]+\))",
        lambda m: m.group(1) + _save(re.match(r".*", m.group(2))),
        text,
    )
    # 保护普通链接 [text](url) 的 (url)
    text = re.sub(
        r"(\[[^\]]+\])(\([^)]+\))",
        lambda m: m.group(1) + _save(re.match(r".*", m.group(2))),
        text,
    )
    # 保护行间与行内公式
    text = re.sub(r"\$\$[\s\S]*?\$\$", _save, text)
    text = re.sub(r"\$[^$\n]+\$", _save, text)
    # 保护行内代码
    text = re.sub(r"`[^`\n]+`", _save, text)
    return text, protected


def restore_spans(text: str, protected: list[str]) -> str:
    for idx in range(len(protected) - 1, -1, -1):
        text = text.replace(f"@@PROT_{idx}@@", protected[idx])
    return text


def _safe_truncate(s: str, max_len: int) -> str:
    """按完整公式 $...$ 与行内代码 `...` 为原子单元截断字符串，绝不截断在公式或代码内部。"""
    tokens = re.split(r"(\$[^$\n]+\$|`[^`\n]+`)", s)
    out = []
    cur_len = 0
    for tok in tokens:
        if not tok:
            continue
        if cur_len + len(tok) > max_len and cur_len > 0:
            return "".join(out) + "……"
        out.append(tok)
        cur_len += len(tok)
    res = "".join(out)
    return res


def extract_diff_snippets(orig: str, pol: str, max_pairs: int = 2) -> list[tuple[str, str]]:
    """按句切分，提取原文与润色稿之间最具代表性的具体改写片段对，供审读说明精准引用。"""
    if orig.strip() == pol.strip():
        return []
    orig_sents = [s.strip() for s in re.split(r"(?<=[。！？；\n])", orig) if s.strip()]
    pol_sents = [s.strip() for s in re.split(r"(?<=[。！？；\n])", pol) if s.strip()]
    pairs = []
    sm = difflib.SequenceMatcher(None, orig_sents, pol_sents)
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "replace":
            o_chunk = "".join(orig_sents[i1:i2]).strip()
            p_chunk = "".join(pol_sents[j1:j2]).strip()
            if o_chunk and p_chunk and o_chunk != p_chunk:
                o_chunk = _safe_truncate(o_chunk, 52)
                p_chunk = _safe_truncate(p_chunk, 56)
                pairs.append((o_chunk, p_chunk))
                if len(pairs) >= max_pairs:
                    break
    return pairs


