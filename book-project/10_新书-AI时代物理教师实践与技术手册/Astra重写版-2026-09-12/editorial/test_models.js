/* 独立数值与边界检查。运行：node editorial/test_models.js */
'use strict';
const P=require('../exercises/models.js');
const fs=require('fs'),path=require('path');
const results=[];
function check(name, fn){try{if(!fn())throw Error('断言不成立');results.push({name,passed:true});}catch(e){results.push({name,passed:false,error:e.message});}}
const near=(a,b,eps=1e-9)=>Math.abs(a-b)<=eps;
const throws=fn=>{try{fn();return false;}catch{return true;}};
const p={f:50,n:1,g:9.8,a0:0,a1:1.82,a2:4,b0:1.82,b1:4,b2:6.54};
const r=P.paper(p);
check('纸带：T=0.02 s',()=>near(r.T,.02));
check('纸带：vA=1.00 m/s',()=>near(r.vA,1));
check('纸带：vB=1.18 m/s',()=>near(r.vB,1.18));
check('纸带：Δh=0.0218 m',()=>near(r.dh,.0218));
check('纸带：gΔh=0.21364',()=>near(r.potential,.21364));
check('纸带：ΔK/m=0.19620',()=>near(r.kinetic,.1962));
check('纸带：差值保留为+0.01744',()=>near(r.D,.01744));
check('纸带：允许两组共用计数点',()=>Number.isFinite(P.paper(p).vB));
check('纸带：拒绝零频率',()=>throws(()=>P.paper({...p,f:0})));
check('纸带：拒绝零周期数',()=>throws(()=>P.paper({...p,n:0})));
check('纸带：拒绝非整数周期数',()=>throws(()=>P.paper({...p,n:1.5})));
check('纸带：拒绝零g',()=>throws(()=>P.paper({...p,g:0})));
check('纸带：拒绝缺失/非数值',()=>throws(()=>P.paper({...p,a1:NaN})));
check('纸带：拒绝同组位置不递增',()=>throws(()=>P.paper({...p,a2:p.a1})));
check('纸带：拒绝B不在A之后',()=>throws(()=>P.paper({...p,b1:1})));
const s={m:1,k:4,A:.2,t:0},s0=P.spring(s),sq=P.spring({...s,t:Math.PI/4}),sh=P.spring({...s,t:Math.PI/2}),s3=P.spring({...s,t:3*Math.PI/4});
check('弹簧：角频率2 rad/s',()=>near(s0.w,2));
check('弹簧：周期π s',()=>near(s0.T,Math.PI));
check('弹簧：初位移0.2 m',()=>near(s0.x,.2));
check('弹簧：初速度0',()=>near(s0.v,0));
check('弹簧：初加速度−0.8',()=>near(s0.a,-.8));
check('弹簧：机械能0.08 J',()=>near(s0.E,.08));
check('弹簧：T/4位移0',()=>near(sq.x,0));
check('弹簧：T/4速度−0.4',()=>near(sq.v,-.4));
check('弹簧：T/4加速度0',()=>near(sq.a,0));
check('弹簧：T/4动能0.08 J',()=>near(sq.K,.08));
check('弹簧：T/2位移−0.2',()=>near(sh.x,-.2));
check('弹簧：T/2加速度+0.8',()=>near(sh.a,.8));
check('弹簧：3T/4速度+0.4',()=>near(s3.v,.4));
check('弹簧：拒绝零质量',()=>throws(()=>P.spring({...s,m:0})));
check('弹簧：1000个时刻能量一致',()=>Array.from({length:1000},(_,i)=>P.spring({...s,t:i*.031})).every(v=>near(v.E,.08)));
const q={a:0,b:10,p:4,U:6};
check('平行板：初始固定点2.4 V',()=>near(P.potential(q).V,2.4));
check('平行板：初始场强60 V/m',()=>near(P.potential(q).E,60));
check('平行板：初始间距10 cm',()=>near(P.potential(q).d,10));
check('平行板：下板上移后1.5 V',()=>near(P.potential({...q,a:2}).V,1.5));
check('平行板：下板上移后75 V/m',()=>near(P.potential({...q,a:2}).E,75));
check('平行板：上板下移后3.0 V',()=>near(P.potential({...q,b:8}).V,3));
check('平行板：上板下移后75 V/m',()=>near(P.potential({...q,b:8}).E,75));
check('平行板：拒绝点落在板上',()=>throws(()=>P.potential({...q,p:0})));
check('平行板：拒绝点位于板外',()=>throws(()=>P.potential({...q,p:12})));
check('平行板：拒绝零间距',()=>throws(()=>P.potential({...q,b:0})));
check('平行板：本练习拒绝负端电压',()=>throws(()=>P.potential({...q,U:-1})));
check('平行板：零端电压得到零电势',()=>near(P.potential({...q,U:0}).V,0));
const c={R:10000,C:100e-6,U:5,V0:0,dt:0,mode:'charge'},c0=P.rc(c),c1=P.rc({...c,dt:1});
check('RC：时间常数1 s',()=>near(c0.tau,1));
check('RC：初始电容电压0',()=>near(c0.V,0));
check('RC：初始电流0.5 mA',()=>near(c0.i,.0005));
check('RC：充电1τ后3.16060279 V',()=>near(c1.V,5*(1-Math.exp(-1))));
check('RC：充电1τ电流',()=>near(c1.i,.0005*Math.exp(-1)));
const d0=P.rc({...c,V0:c1.V,mode:'discharge'}),d1=P.rc({...c,V0:c1.V,mode:'discharge',dt:1});
check('RC：切换瞬间电压连续',()=>near(d0.V,c1.V));
check('RC：继续放电1τ得到1.16272079 V',()=>near(d1.V,5*(Math.exp(-1)-Math.exp(-2))));
check('RC：放电电流为负',()=>d0.i<0);
check('RC：切回充电不重置电压',()=>near(P.rc({...c,V0:d1.V}).V,d1.V));
check('RC：拒绝零电阻',()=>throws(()=>P.rc({...c,R:0})));
check('RC：拒绝零电容',()=>throws(()=>P.rc({...c,C:0})));
check('RC：拒绝负时间增量',()=>throws(()=>P.rc({...c,dt:-1})));
check('RC：分步计算与整步一致',()=>near(P.rc({...c,V0:P.rc({...c,dt:.4}).V,dt:.6}).V,c1.V));
const report={type:'解析模型数值与输入边界检查',total:results.length,passed:results.filter(x=>x.passed).length,failed:results.filter(x=>!x.passed).length,limitations:['非硬件实测','非课堂有效性检验','不覆盖全部浏览器行为'],results};
fs.writeFileSync(path.join(__dirname,'model-test-report.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify({total:report.total,passed:report.passed,failed:report.failed}));
if(report.failed)process.exitCode=1;
